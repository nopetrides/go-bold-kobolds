		/// <summary>
		///     Generates mesh data from a chunk's density field using marching cubes.
		/// </summary>
		/// <param name="densityField">NativeArray of 512 bytes (0-255) representing the chunk's density.</param>
		/// <param name="vertices">Output list of mesh vertices (UnityEngine.Vector3).</param>
		/// <param name="triangles">Output list of mesh triangle indices (16-bit).</param>
		/// <param name="normals">Output list of mesh normals (UnityEngine.Vector3).</param>
		/// <param name="generateSmoothNormals">If true, generate smooth per-vertex normals; otherwise, flat shading.</param>
		public static void GenerateMesh(
			NativeArray<byte> densityField,
			List<Vector3> vertices,
			List<int> triangles,
			List<Vector3> normals,
			bool generateSmoothNormals = true)
		{
			// Clear output lists
			vertices.Clear();
			triangles.Clear();
			normals.Clear();

			// Dictionary to cache vertex indices for smooth normals (key: grid position + edge)
			var vertexCache = generateSmoothNormals ? new Dictionary<long, int>(4096) : null;

			// Iterate over all unit cubes in the chunk (7x7x7 cubes, each with 8 corners)
			for (var z = 0; z < ChunkSize - 1; z++)
			{
				for (var y = 0; y < ChunkSize - 1; y++)
				{
					for (var x = 0; x < ChunkSize - 1; x++)
					{
						// Compute the 8 corner indices for this cube
						var cornerIndices = new int[8];
						for (var i = 0; i < 8; i++)
						{
							var corner = new int3(x, y, z) + CornerOffset(i);
							cornerIndices[i] = corner.z * ChunkSize * ChunkSize + corner.y * ChunkSize + corner.x;
						}

						// Get the 8 corner densities
						var cornerDensities = new byte[8];
						for (var i = 0; i < 8; i++) cornerDensities[i] = densityField[cornerIndices[i]];
						// Calculate the cube index (bitmask of which corners are solid)
						var cubeIndex = 0;
						for (var i = 0; i < 8; i++)
							if (cornerDensities[i] >= Threshold)
								cubeIndex |= 1 << i;
						// If the cube is entirely inside or outside, skip
						if (cubeIndex == 0 || cubeIndex == 255)
							continue;
						// For each triangle in this configuration
						for (var t = 0; TriangleTable[cubeIndex, t] != -1; t += 3)
						{
							var triVerts = new int[3];
							var triPositions = new Vector3[3];
							var triNormals = new Vector3[3];
							// For each vertex of the triangle
							for (var v = 0; v < 3; v++)
							{
								var edge = TriangleTable[cubeIndex, t + v];
								// Get the two corner indices for this edge
								var c0 = EdgeCornerA(edge);
								var c1 = EdgeCornerB(edge);
								// Interpolate vertex position along the edge
								var p0 = new float3(x, y, z) + CornerOffset(c0);
								var p1 = new float3(x, y, z) + CornerOffset(c1);
								float d0 = cornerDensities[c0];
								float d1 = cornerDensities[c1];
								var tEdge = math.saturate((Threshold - d0) / math.max(1e-5f, d1 - d0));
								var pos = math.lerp(p0, p1, tEdge);
								var posV3 = new Vector3(pos.x, pos.y, pos.z);
								// For smooth normals, cache/reuse vertex index
								int vertIndex;
								if (generateSmoothNormals)
								{
									var key = VertexCacheKey(x, y, z, edge);
									if (!vertexCache.TryGetValue(key, out vertIndex))
									{
										vertIndex = vertices.Count;
										vertices.Add(posV3);
										normals.Add(Vector3.zero); // Placeholder, will accumulate
										vertexCache[key] = vertIndex;
									}
								}
								else
								{
									vertIndex = vertices.Count;
									vertices.Add(posV3);
									normals.Add(Vector3.zero); // Placeholder
								}

								triVerts[v] = vertIndex;
								triPositions[v] = posV3;
							}

							// Add triangle indices
							triangles.Add(triVerts[0]);
							triangles.Add(triVerts[1]);
							triangles.Add(triVerts[2]);
							// Compute face normal
							var faceNormal = Vector3.Cross(
								triPositions[1] - triPositions[0], triPositions[2] - triPositions[0]).normalized;
							// Accumulate normals
							for (var v = 0; v < 3; v++)
								if (generateSmoothNormals)
									normals[triVerts[v]] += faceNormal;
								else
									normals[triVerts[v]] = faceNormal;
						}
					}
				}
			}

			// Normalize normals for smooth shading
			if (generateSmoothNormals)
				for (var i = 0; i < normals.Count; i++)
					normals[i] = normals[i].normalized;
		}

		/// <summary>
		///     Overload for byte[512] density field.
		/// </summary>
		public static void GenerateMesh(
			byte[] densityField,
			List<Vector3> vertices,
			List<int> triangles,
			List<Vector3> normals,
			bool generateSmoothNormals = true)
		{
			// Wrap the array in a NativeArray (temporary, Allocator.Temp)
			using (var native = new NativeArray<byte>(densityField, Allocator.Temp))
			{
				GenerateMesh(native, vertices, triangles, normals, generateSmoothNormals);
			}
		}

		// Returns the offset for a given corner index (0-7)
		private static int3 CornerOffset(int i)
		{
			// 8 corners of a cube
			switch (i)
			{
				case 0: return new int3(0, 0, 0);
				case 1: return new int3(1, 0, 0);
				case 2: return new int3(1, 1, 0);
				case 3: return new int3(0, 1, 0);
				case 4: return new int3(0, 0, 1);
				case 5: return new int3(1, 0, 1);
				case 6: return new int3(1, 1, 1);
				case 7: return new int3(0, 1, 1);
				default: return int3.zero;
			}
		}

		// Returns the first corner index for a given edge (0-11)
		private static int EdgeCornerA(int edge)
		{
			// Edge to corner mapping
			var edgeToCorner = new int[12, 2]
			{
				{0, 1}, {1, 2}, {2, 3}, {3, 0}, // bottom face
				{4, 5}, {5, 6}, {6, 7}, {7, 4}, // top face
				{0, 4}, {1, 5}, {2, 6}, {3, 7} // vertical edges
			};
			return edgeToCorner[edge, 0];
		}

		// Returns the second corner index for a given edge (0-11)
		private static int EdgeCornerB(int edge)
		{
			var edgeToCorner = new int[12, 2]
			{
				{0, 1}, {1, 2}, {2, 3}, {3, 0},
				{4, 5}, {5, 6}, {6, 7}, {7, 4},
				{0, 4}, {1, 5}, {2, 6}, {3, 7}
			};
			return edgeToCorner[edge, 1];
		}

		// Generates a unique key for a vertex on a cube edge for caching
		private static long VertexCacheKey(int x, int y, int z, int edge)
		{
			// Pack x, y, z, edge into a 32-bit or 64-bit key
			return ((long) x << 24) | ((long) y << 16) | ((long) z << 8) | edge;
		}
